import { Router } from "express";
import crypto from "node:crypto";
import { authenticateApiKey } from "../middleware/apiKeyAuth.js";
import { findPiiViolation } from "../services/capabilities.js";
import { VALID_SAFEGUARD_SUBTOPICS } from "../services/safeguardClearance.js";
import {
  createRiskFlagRecord,
  getCohortClusterSummary,
  getLatestRiskFlag,
} from "../db/firestore.js";

const router = Router();

// Reuse the exact same API key authentication middleware as /api/public/v1/* and /mcp
router.use(authenticateApiKey);

// Additional safeguard guard: reject any rupee/currency-like key names too
const EXTRA_CURRENCY_KEY_RE =
  /(loss[_-]?amount|pnl|rupee|inr|amount|capital|margin[_-]?rs|balance|net[_-]?worth|account|pan|client[_-]?id|phone|email)/i;

function findPartnerPayloadViolation(body) {
  const baseViolation = findPiiViolation(body);
  if (baseViolation) return baseViolation;

  if (body && typeof body === "object") {
    for (const key of Object.keys(body)) {
      if (EXTRA_CURRENCY_KEY_RE.test(key)) {
        return `Forbidden PII or currency field "${key}" is not accepted`;
      }
    }
  }
  return null;
}

/**
 * POST /api/partner/v1/risk-flag
 * Body: { external_user_ref: string, flagged_subtopic: string, flagged_at?: string }
 *
 * Accepts an anonymized broker risk flag (zero PII, zero ₹ amounts).
 * Partners can NEVER set cleared=true — only Samajh's scoring pipeline can clear a flag.
 */
router.post("/risk-flag", async (req, res, next) => {
  try {
    const body = req.body || {};

    // Never log req.body when PII/currency is rejected
    const piiViolation = findPartnerPayloadViolation(body);
    if (piiViolation) {
      return res.status(400).json({
        error: `Privacy guard rejected payload: ${piiViolation}. Send only anonymized external_user_ref and taxonomy subtopic.`,
      });
    }

    // Partners must never be allowed to set cleared=true directly
    if ("cleared" in body || "cleared_at" in body || "credential_id" in body) {
      return res.status(400).json({
        error:
          "Partners cannot set clearance fields directly. Clearance is granted only after the user passes Teach-Back + Stress-Test.",
      });
    }

    const external_user_ref =
      typeof body.external_user_ref === "string" ? body.external_user_ref.trim() : "";
    const flagged_subtopic =
      typeof body.flagged_subtopic === "string" ? body.flagged_subtopic.trim() : "";
    const flagged_at_raw =
      typeof body.flagged_at === "string" ? body.flagged_at.trim() : new Date().toISOString();

    if (external_user_ref.length < 3 || external_user_ref.length > 128) {
      return res.status(400).json({
        error: "external_user_ref must be an anonymized string between 3 and 128 characters.",
      });
    }

    if (!VALID_SAFEGUARD_SUBTOPICS.includes(flagged_subtopic)) {
      return res.status(400).json({
        error: `Invalid flagged_subtopic "${flagged_subtopic}". Must be one of: ${VALID_SAFEGUARD_SUBTOPICS.join(", ")}.`,
      });
    }

    const parsedDate = new Date(flagged_at_raw);
    if (Number.isNaN(parsedDate.getTime())) {
      return res.status(400).json({ error: "flagged_at must be a valid ISO-8601 timestamp." });
    }

    const record = await createRiskFlagRecord({
      id: `rf_${crypto.randomUUID()}`,
      partnerUserId: req.apiKeyAuth.userId,
      external_user_ref,
      flagged_subtopic,
      flagged_at: parsedDate.toISOString(),
    });

    return res.status(201).json({
      id: record.id,
      external_user_ref: record.external_user_ref,
      flagged_subtopic: record.flagged_subtopic,
      flagged_at: record.flagged_at,
      cleared: false,
    });
  } catch (err) {
    return next(err);
  }
});

/**
 * GET /api/partner/v1/clearance-status/:external_user_ref
 * Returns { cleared: boolean, cleared_at, credential_id } for the partner to poll.
 */
router.get("/clearance-status/:external_user_ref", async (req, res, next) => {
  try {
    const externalRef = req.params.external_user_ref?.toString().trim();
    if (!externalRef) {
      return res.status(400).json({ error: "external_user_ref is required." });
    }

    const record = await getLatestRiskFlag(externalRef, req.apiKeyAuth.userId);
    if (!record) {
      return res.status(404).json({ error: "No risk flag found for this external_user_ref." });
    }

    return res.status(200).json({
      external_user_ref: record.external_user_ref,
      flagged_subtopic: record.flagged_subtopic,
      cleared: Boolean(record.cleared),
      cleared_at: record.cleared_at ?? null,
      credential_id: record.credential_id ?? null,
    });
  } catch (err) {
    return next(err);
  }
});

/**
 * GET /api/partner/v1/cohort-insights/:partner_id
 * Returns ONLY pre-computed, aggregate-only misconception clusters generated by the
 * scheduled batch clustering job (NEVER triggers clustering per-request, NEVER returns
 * any individual userId, uid, email, displayName, or sessionId).
 */
router.get("/cohort-insights/:partner_id", async (req, res, next) => {
  try {
    const partnerId = req.params.partner_id?.toString().trim();
    if (!partnerId || partnerId.length > 128) {
      return res.status(400).json({ error: "Valid partner_id is required." });
    }

    const summary = await getCohortClusterSummary(partnerId);
    if (!summary) {
      return res.status(200).json({
        partner_id: partnerId,
        computed_at: null,
        total_sessions_analyzed: 0,
        cluster_count: 0,
        vector_backend: "vertex-ai-vector-search",
        aggregate_only: true,
        clusters: [],
      });
    }

    return res.status(200).json({
      partner_id: summary.partner_id,
      computed_at: summary.computed_at,
      total_sessions_analyzed: Number(summary.total_sessions_analyzed || 0),
      cluster_count: (summary.clusters || []).length,
      vector_backend: summary.vector_backend,
      aggregate_only: true,
      clusters: (summary.clusters || []).map((c, idx) => ({
        rank: c.rank ?? idx + 1,
        cluster_id: c.cluster_id,
        label: c.label,
        primary_subtopic: c.primary_subtopic,
        session_count: Number(c.session_count || 0),
        pct_of_cohort: Number(c.pct_of_cohort || 0),
        top_themes: Array.isArray(c.top_themes) ? c.top_themes : [],
      })),
    });
  } catch (err) {
    return next(err);
  }
});

router.use((err, _req, res, _next) => {
  const status = err.statusCode || err.status || 500;
  if (status >= 400 && status < 500) {
    return res.status(status).json({ error: err.message || "Bad request" });
  }
  console.error("[Samajh Partner API v1 Error]", err);
  return res.status(500).json({ error: "internal_error" });
});

export default router;
